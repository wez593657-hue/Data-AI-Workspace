                         AND CNTCT_RATE=33.33 AND RESCUED_CUST_CNT=1 AND RESCUE_RATE=33.33 AND RESCUED_FINA_ASSET=150000)
                     OR (STATIS_OBJ='PM100' AND LVL_CHURN='1' AND CUST_CNT=3 AND CNTCT_RATE=33.33 AND RESCUE_RATE=33.33 AND RESCUED_FINA_ASSET=15000)
                     OR (STATIS_OBJ='PM100' AND LVL_CHURN='2' AND CUST_CNT=2 AND CNTCT_RATE=50 AND RESCUE_RATE=50 AND RESCUED_FINA_ASSET=150000)) = 4
            THEN 'PASS' ELSE 'FAIL' END AS F8_ROLLUP

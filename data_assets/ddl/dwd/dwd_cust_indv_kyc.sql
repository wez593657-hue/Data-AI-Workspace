COMMENT ON COLUMN DWD_CUST_INDV_KYC.ESTT_INF IS '住宅信息';
COMMENT ON COLUMN DWD_CUST_INDV_KYC.PROP_OWNER_CERT_NO IS '房产证号';
COMMENT ON COLUMN DWD_CUST_INDV_KYC.HOUSE_AREA IS '面积';
